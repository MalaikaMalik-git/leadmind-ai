// backend/src/models/Meeting.js
// LeadMind AI — Meeting model
// ERD entity: Meetings (section 2.12)
// Related UCs: UC-13 (Book Meeting), UC-06 (Calendar config)
//
// Key spec requirements implemented:
// - "Store event ID for traceability and audit" (UC-13 special requirements)
// - "Prevent double booking — re-check availability before event creation" (UC-13)
// - "Time zone handling must remain consistent between system and Google Calendar" (UC-13)
// - Lead status updates to "Meeting Booked" after successful booking (handled in controller)

const mongoose = require('mongoose');

// ─── Constants ────────────────────────────────────────────────────────────────
const MEETING_STATUS = Object.freeze({
  SCHEDULED:    'Scheduled',
  COMPLETED:    'Completed',
  CANCELLED:    'Cancelled',
  RESCHEDULED:  'Rescheduled',
  NO_SHOW:      'No Show',
});

const GOOGLE_SYNC_STATUS = Object.freeze({
  PENDING: 'Pending',
  SYNCED:  'Synced',
  FAILED:  'Failed',
});

// ─── Schema ───────────────────────────────────────────────────────────────────
const MeetingSchema = new mongoose.Schema(
  {
    // ── References ─────────────────────────────────────────────────────────────
    lead: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'Lead',
      required: [true, 'Lead reference is required'],
    },

    // null for inbound-originated meetings with no campaign
    campaign: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'Campaign',
      default: null,
    },

    // The call transcript during which meeting was booked
    transcript: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'Transcript',
      default: null,
    },

    // null = booked automatically by AI during call; set when admin books manually
    bookedBy: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'Admin',
      default: null,
    },

    // ── Core fields ────────────────────────────────────────────────────────────
    title: {
      type: String,
      required: [true, 'Meeting title is required'],
      trim: true,
      maxlength: [200, 'Title cannot exceed 200 characters'],
      default: 'LeadMind AI — Discovery Call',
    },

    description: {
      type: String,
      trim: true,
      maxlength: [1000, 'Description cannot exceed 1000 characters'],
      default: null,
    },

    // Always stored in UTC — convert on display using timezone field
    scheduledAt: {
      type: Date,
      required: [true, 'Scheduled date/time is required'],
    },

    durationMinutes: {
      type: Number,
      required: [true, 'Duration is required'],
      min:  [15,  'Minimum duration is 15 minutes'],
      max:  [180, 'Maximum duration is 180 minutes'],
      default: 30,
    },

    // IANA timezone — must match admin Google Calendar timezone (UC-13 spec)
    timezone: {
      type: String,
      required: [true, 'Timezone is required'],
      default: 'Asia/Karachi',
    },

    status: {
      type: String,
      enum: {
        values:   Object.values(MEETING_STATUS),
        message:  'Invalid meeting status',
      },
      default: MEETING_STATUS.SCHEDULED,
    },

    // ── Google Calendar (UC-13: "store event ID for traceability and audit") ──
    googleCalendar: {
      eventId: {
        type:    String,
        default: null,
      },
      // Google Meet link generated by Calendar API (if available)
      meetingLink: {
        type:    String,
        default: null,
      },
      calendarId: {
        type:    String,
        default: 'primary',
      },
      syncStatus: {
        type: String,
        enum: {
          values:  Object.values(GOOGLE_SYNC_STATUS),
          message: 'Invalid sync status',
        },
        default: GOOGLE_SYNC_STATUS.PENDING,
      },
      syncedAt: {
        type:    Date,
        default: null,
      },
      // Stores error detail when sync fails — useful for retrying without data loss
      syncError: {
        type:    String,
        default: null,
      },
      // Raw Google Calendar API response — excluded from normal queries
      rawEventData: {
        type:    mongoose.Schema.Types.Mixed,
        default: null,
        select:  false,
      },
    },

    // ── Invitation email ───────────────────────────────────────────────────────
    // How (and whether) the lead was told about this meeting.
    //   'smtp'   = our own transactional email (SPF/DKIM-authenticated, best inbox placement)
    //   'google' = Google Calendar's native invitation (fallback when SMTP is not configured / failed)
    //   'none'   = nothing was sent (lead has no email address)
    invite: {
      channel: { type: String, enum: ['smtp', 'google', 'none'], default: 'none' },
      sentTo:  { type: String, default: null },
      sentAt:  { type: Date,   default: null },
      error:   { type: String, default: null },
    },

    // ── Lead snapshot ──────────────────────────────────────────────────────────
    // Captured at booking time so meeting record stays accurate if lead data changes later
    leadSnapshot: {
      fullName: { type: String, default: null },
      phone:    { type: String, default: null },
      email:    { type: String, default: null },
      company:  { type: String, default: null },
    },

    notes: {
      type:      String,
      trim:      true,
      maxlength: [1000, 'Notes cannot exceed 1000 characters'],
      default:   null,
    },

    // ── Cancellation / reschedule ──────────────────────────────────────────────
    cancelledAt: { type: Date,   default: null },
    cancelReason: {
      type:      String,
      trim:      true,
      maxlength: [500, 'Cancel reason cannot exceed 500 characters'],
      default:   null,
    },

    // Points to the replacement Meeting doc when this one is rescheduled
    rescheduledTo: {
      type:    mongoose.Schema.Types.ObjectId,
      ref:     'Meeting',
      default: null,
    },
  },
  {
    timestamps: true,
    toJSON:   { virtuals: true },
    toObject: { virtuals: true },
  }
);

// ─── Virtuals ─────────────────────────────────────────────────────────────────
// Computed end time — used for overlap/conflict detection in the booking service
MeetingSchema.virtual('scheduledEnd').get(function () {
  if (!this.scheduledAt) return null;
  return new Date(this.scheduledAt.getTime() + this.durationMinutes * 60 * 1000);
});

MeetingSchema.virtual('isUpcoming').get(function () {
  return this.scheduledAt > new Date() && this.status === MEETING_STATUS.SCHEDULED;
});

// ─── Indexes ──────────────────────────────────────────────────────────────────
// Compound index for double-booking check: find overlapping scheduled meetings
MeetingSchema.index({ scheduledAt: 1, status: 1 });
MeetingSchema.index({ lead: 1 });
MeetingSchema.index({ campaign: 1, scheduledAt: -1 });
// sparse: true — only indexes docs that have an eventId (skips nulls)
MeetingSchema.index({ 'googleCalendar.eventId': 1 }, { sparse: true });
MeetingSchema.index({ createdAt: -1 });

// ─── Export ───────────────────────────────────────────────────────────────────
const Meeting = mongoose.model('Meeting', MeetingSchema);

module.exports = Meeting;
module.exports.MEETING_STATUS    = MEETING_STATUS;
module.exports.GOOGLE_SYNC_STATUS = GOOGLE_SYNC_STATUS;